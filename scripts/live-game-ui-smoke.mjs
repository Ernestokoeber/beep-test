const {openLiveGame}=await import('../js/live-game/controller.mjs');
const {mountLiveView}=await import('../js/live-game/view.mjs');
const dom=new JSDOM('<main></main>',{url:'https://local.test'});
globalThis.document=dom.window.document;
const scope={organizationId:'ui-org',actorId:'u',sessionEpoch:1};
