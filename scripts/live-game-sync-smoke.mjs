import assert from 'node:assert/strict';
import {existsSync} from 'node:fs';
import {indexedDB} from 'fake-indexeddb';
import {createSession,appendEvent} from '../js/live-game/core.mjs';
assert.ok(existsSync(new URL('../js/live-game/bridge.mjs',import.meta.url)),'Live-Synchronisierung fehlt');
const {openJournal}=await import('../js/live-game/journal.mjs');
const {mergeLiveStats,protectWorkspace}=await import('../js/live-game/merge.mjs');
const {createBridge}=await import('../js/live-game/bridge.mjs');
const scope={organizationId:'org',actorId:'u',sessionEpoch:1};
const journal=await openJournal(scope,indexedDB);
let s=createSession({id:'s',actorId:'u',deviceId:'d',roster:Array.from({length:5},(_,i)=>({id:'p'+i,name:'P'+i})),startingFive:['p0','p1','p2','p3','p4'],config:{periods:4,periodMs:600000,overtimeMs:300000}});
const live=session=>({schemaVersion:1,sessions:[session],selectedSessionId:session.id,resolutionRevision:0});
s.schemaVersion=2;
const workspace={games:[{id:'g',liveStats:live(s)}]};
await journal.append('g',live(s));
const bridge=createBridge(()=>journal);
const first=await bridge.beforeSend(workspace,scope);
const e={id:'e1',sessionId:'s',seq:1,period:1,remainingMs:600000,recordedAt:'2026-09-29T18:00:00Z',kind:'opponent-score',payload:{points:2}};
s=appendEvent(s,e);await journal.append('g',live(s));
await bridge.ack(first.receipt,scope);
assert.equal((await journal.pending()).length,1);
const restored=await bridge.beforeApply({games:[{id:'g'}]},scope);
assert.equal(restored.games[0].liveStats.sessions[0].events.length,1);
assert.equal(mergeLiveStats(live(s),live(s)).value.sessions[0].events.length,1);
const bad=structuredClone(s);bad.events[0].payload.points=3;
assert.throws(()=>mergeLiveStats(live(s),live(bad)),/Konflikt/);
assert.throws(()=>protectWorkspace({games:[]},restored),/Lösch/);
assert.equal(protectWorkspace({games:[]},restored,['g']).games.length,0);
assert.equal(protectWorkspace({games:[{id:'g',score:'50:40'}]},restored).games[0].liveStats.sessions[0].events.length,1);
const other=await openJournal({...scope,organizationId:'other'},indexedDB);
assert.equal((await other.pending()).length,0);
await journal.acquire('g','tab1',1000);await assert.rejects(()=>journal.acquire('g','tab2',1001));
await journal.release('g','tab1');await journal.acquire('g','tab2',1002);
const snapshot=await bridge.beforeSend(restored,scope);await bridge.ack(snapshot.receipt,scope);
assert.equal((await journal.pending()).length,0);
assert.equal((await journal.read('g')).sessions[0].events.length,1);
const second=structuredClone(s);second.id='other-session';second.deviceId='other-device';second.events=second.events.map(e=>({...e,sessionId:second.id}));
const concurrent=mergeLiveStats(live(s),live(second));assert.equal(concurrent.value.sessions.length,2);assert.equal(concurrent.value.selectedSessionId,null);
const selected={...concurrent.value,selectedSessionId:s.id,resolutionRevision:1};
assert.equal(mergeLiveStats(selected,concurrent.value).value.selectedSessionId,s.id);
const otherActor=await openJournal({...scope,actorId:'another'},indexedDB);assert.equal((await otherActor.pending()).length,0);
const colliding=structuredClone(s);colliding.events[0].id='another-id';assert.throws(()=>mergeLiveStats(live(s),live(colliding)),{code:'sequence'});
await journal.append('g',live(s));await assert.rejects(()=>bridge.beforeApply({games:[]},scope),/entfernt/);assert.equal((await journal.pending()).length,1);
console.log('Live sync: durable journal, exact receipts, identity isolation, leases, merge and deletion guard passed.');
