import { readFileSync } from 'node:fs';
import vm from 'node:vm';
import { dirname, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
let sequence = 0;
globalThis.window = globalThis;
globalThis.BT = { util: { uuid: (prefix = 'id_') => `${prefix}${++sequence}` } };
vm.runInThisContext(readFileSync(resolve(root, 'js/tactics.js'), 'utf8'), {
  filename: 'js/tactics.js'
});
await import(pathToFileURL(resolve(root, 'js/play-designer/timing-fix.js')).href + '?defense=1');
const quick = await import(
  pathToFileURL(resolve(root, 'js/play-designer/quick-core.js')).href + '?defense=1'
);
const recorder = await import(
  pathToFileURL(resolve(root, 'js/play-designer/phase-recorder-core.js')).href + '?defense=1'
);

function assert(condition, message) {
  if (!condition) throw new Error(message);
}

function near(left, right, tolerance = 0.01) {
  return Math.abs(left - right) <= tolerance;
}

const core = globalThis.BT.tactics.__core;
let board = core.defaultBoard();
board = quick.addQuickMove(board, {
  stepIndex: 0,
  relation: 'after',
  actorId: 'o1',
  path: [
    { x: 250, y: 388 },
    { x: 280, y: 330 },
    { x: 330, y: 250 }
  ]
}, core);

let first = board.steps[0];
let follow = first.transition.motions.find(action =>
  action.autoGenerated === 'defender-follow' && action.followsId === 'o1'
);
assert(follow, 'Ein Mannverteidiger folgt dem offensiven Laufweg nicht automatisch.');
assert(follow.elementId === 'd1', 'Der nächstgelegene Mannverteidiger wird nicht zugeordnet.');
assert(follow.start > 0, 'Der Verteidiger besitzt keine Reaktionsverzögerung.');
assert(
  recorder.recordedActions(first, core).every(action => action.autoGenerated !== 'defender-follow'),
  'Automatische Defense überfrachtet die bearbeitbare Aktionsliste.'
);

board = quick.addQuickScreen(board, {
  stepIndex: 0,
  relation: 'same',
  actorId: 'o5',
  beneficiaryId: 'o1',
  targetDefenderId: 'd1',
  point: core.elementById(first, 'o5')
}, core);
first = board.steps[0];
follow = first.transition.motions.find(action =>
  action.autoGenerated === 'defender-follow' && action.followsId === 'o1'
);
assert(follow?.holds?.length === 1, 'Der gebundene Screen hält den Zielverteidiger nicht kurz auf.');
assert(follow.holds[0].screenId === first.transition.screens[0].id, 'Die Screenpause ist nicht an den Screen gebunden.');

const hold = follow.holds[0];
const justBeforeHold = globalThis.BT.tactics.snapshotAt(board, Math.max(follow.start, hold.at - 0.01));
const duringHold = globalThis.BT.tactics.snapshotAt(board, hold.at + hold.duration * 0.7);
const afterHold = globalThis.BT.tactics.snapshotAt(board, Math.min(
  follow.start + follow.duration - 0.02,
  hold.at + hold.duration + 0.2
));
const beforeDefender = core.elementById(justBeforeHold, follow.elementId);
const heldDefender = core.elementById(duringHold, follow.elementId);
const resumedDefender = core.elementById(afterHold, follow.elementId);
assert(
  near(beforeDefender.x, heldDefender.x) && near(beforeDefender.y, heldDefender.y),
  'Der Verteidiger bleibt während des Screens nicht stehen.'
);
assert(
  !near(heldDefender.x, resumedDefender.x) || !near(heldDefender.y, resumedDefender.y),
  'Der Verteidiger nimmt die Verfolgung nach dem Screen nicht wieder auf.'
);

const finalSnapshot = globalThis.BT.tactics.snapshotAt(board, first.duration - 0.001);
const finalDefender = core.elementById(finalSnapshot, follow.elementId);
const nextDefender = core.elementById(board.steps[1], follow.elementId);
assert(
  near(finalDefender.x, nextDefender.x, 0.2) && near(finalDefender.y, nextDefender.y, 0.2),
  'Der Verteidiger erreicht nach der Verzögerung seine Folgeposition nicht.'
);

let manualBoard = core.defaultBoard();
const manualFirst = manualBoard.steps[0];
const manualNext = core.cloneStep(manualFirst);
manualBoard.steps.push(manualNext);
manualFirst.transition.motions.push({
  id: 'manual-defense',
  type: 'move',
  elementId: 'd1',
  start: 0,
  duration: 1,
  path: [{ x: 250, y: 338 }, { x: 210, y: 285 }]
});
Object.assign(core.elementById(manualNext, 'd1'), { x: 210, y: 285 });
manualBoard = quick.addQuickMove(manualBoard, {
  stepIndex: 0,
  relation: 'same',
  actorId: 'o1',
  path: [{ x: 250, y: 388 }, { x: 340, y: 250 }]
}, core);
assert(
  manualBoard.steps[0].transition.motions.filter(action => action.elementId === 'd1').length === 1,
  'Ein eigener Defense-Laufweg wird von der Automatik überschrieben.'
);
assert(
  manualBoard.steps[0].transition.motions.find(action => action.elementId === 'd1').id === 'manual-defense',
  'Der manuelle Defense-Laufweg verliert seine Priorität.'
);

let zoneBoard = core.defaultBoard();
zoneBoard.steps[0].elements
  .filter(element => element.type === 'defense')
  .forEach(defender => { defender.defenseMode = 'zone'; });
zoneBoard = quick.addQuickMove(zoneBoard, {
  stepIndex: 0,
  relation: 'after',
  actorId: 'o1',
  path: [{ x: 250, y: 388 }, { x: 300, y: 280 }]
}, core);
assert(
  !zoneBoard.steps[0].transition.motions.some(action => action.autoGenerated === 'defender-follow'),
  'Zonenverteidiger werden fälschlich wie feste Gegenspieler automatisch mitgezogen.'
);

console.log('CourtHub: automatische Mannverteidigung, Reaktionszeit und Screenpause erfolgreich geprüft.');
