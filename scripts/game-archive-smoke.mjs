// The durable live journal can be newer than the workspace after a storage failure.
// Its finish event must still close both editing paths, including after reopening.
const offline=await fixture();let permitAfterFinish=false;
offline.deps.isReadOnly=live=>{
  const session=live?.sessions?.find(item=>item.id===live.selectedSessionId);
  return !permitAfterFinish&&Boolean(session?.events.some(event=>event.kind==='finish'));
};
let oc=await offline.open();
