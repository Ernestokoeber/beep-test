import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { JSDOM } from 'jsdom';
import { protectWorkspace } from '../js/live-game/merge.mjs';

const dom = new JSDOM('<main></main>', { url: 'https://coach.test', runScripts: 'outside-only' });
const w = dom.window;
for (const file of ['util', 'storage', 'jerseys']) w.eval(readFileSync(new URL(`../js/${file}.js`, import.meta.url), 'utf8'));
const BT = w.BT;
BT.util.todayISO = () => '2026-10-09';
w.confirm = () => true;
let saves = 0;
BT.sync = { queueSave() { saves++; }, getState() { return { user: { role: 'coach' } }; } };
const players = ['Adam', 'Boris', 'Carlo'].map(name => BT.storage.upsertPlayer({ name }));
assert.equal(BT.storage.load().jerseyDuties.length, 0, 'Older workspaces get an empty collection.');
const home = BT.storage.upsertJerseyDuty({ kit: 'home', playerId: players[0].id, takenOn: '2026-10-04', dueOn: '2026-10-08', status: 'pending' });
const away = BT.storage.upsertJerseyDuty({ kit: 'away', playerId: players[1].id, takenOn: '2026-10-05', status: 'pending' });
const attempt = values => BT.storage.upsertJerseyDuty({ kit: 'home', playerId: players[2].id, takenOn: '2026-10-06', status: 'pending', ...values });
assert.throws(() => attempt({}), /bereits/);
assert.throws(() => attempt({ kit: 'invalid' }), /Auswärtssatz/);
assert.throws(() => attempt({ playerId: 'missing' }), /aktiven Spieler/);
assert.throws(() => attempt({ playerId: undefined }), /aktiven Spieler/);
assert.throws(() => attempt({ takenOn: '2026-02-30' }), /Vergangenheit/);
assert.throws(() => attempt({ takenOn: '2026-10-10' }), /Vergangenheit/);
assert.throws(() => attempt({ dueOn: '2026-10-01' }), /Mitnahme/);
assert.throws(() => attempt({ status: 'returned', returnedOn: '2026-10-01' }), /sauberen/);
assert.throws(() => attempt({ status: 'returned', returnedOn: '2026-10-10' }), /sauberen/);
const rows = BT.jerseys.workload(BT.storage.getPlayers(), BT.storage.getJerseyDuties(), '26/27');
assert.equal(rows[0].player.id, players[2].id);
assert.equal(rows.find(row => row.player.id === players[0].id).open, 1);
const host = w.document.querySelector('main');
BT.jerseys.render(host);
assert.match(host.querySelector('[data-kit="home"]').textContent, /Adam.*überfällig/s);
assert.match(host.querySelector('[data-kit="away"]').textContent, /Boris/);
host.querySelector('[data-role="jersey-never"]').click();
assert.equal(host.querySelectorAll('[data-player-id]').length, 1);
assert.equal(host.querySelector('[data-player-id]').dataset.playerId, players[2].id);
host.querySelector('[data-kit="home"] [data-action="return"]').click();
assert.equal(BT.storage.getJerseyDuties().find(duty => duty.id === home.id).returnedOn, '2026-10-09');
assert.equal(BT.jerseys.workload(BT.storage.getPlayers(), BT.storage.getJerseyDuties(), '26/27').find(row => row.player.id === players[0].id).total, 1, 'Returning does not count a second duty.');
// Reopening and cancelling must not accumulate submit listeners.
host.querySelector('[data-kit="home"] [data-action="new"]').click();
host.querySelector('[data-action="cancel"]').click();
host.querySelector('[data-kit="home"] [data-action="new"]').click();
const form = host.querySelector('form');
form.elements.playerId.value = players[2].id;
const before = BT.storage.getJerseyDuties().length;
form.dispatchEvent(new w.Event('submit', { bubbles: true, cancelable: true }));
assert.equal(BT.storage.getJerseyDuties().length, before + 1);
assert.match(host.querySelector('[data-kit="home"]').textContent, /Carlo/);
const prior = BT.storage.upsertJerseyDuty({ kit: 'home', playerId: players[2].id, takenOn: '2026-07-01', status: 'returned', returnedOn: '2026-07-02' });
assert.equal(prior.seasonId, '25/26');
const all = BT.jerseys.workload(BT.storage.getPlayers(), BT.storage.getJerseyDuties(), 'all');
assert.equal(all.find(row => row.player.id === players[2].id).total, 2);
BT.storage.setArchived(players[1].id, true);
host.replaceChildren(); BT.jerseys.render(host);
assert.equal(host.querySelectorAll(`[data-player-id="${players[1].id}"]`).length, 0);
assert.match(host.querySelector('[data-kit="away"]').textContent, /Boris/, 'An archived owner must still be visible.');
BT.storage.deletePlayer(players[1].id);
BT.storage.upsertJerseyDuty({ ...away, status: 'returned', returnedOn: '2026-10-09' });
assert.equal(BT.storage.getJerseyDuties().find(duty => duty.id === away.id).playerName, 'Boris', 'Historical names survive removal from the roster.');
BT.storage.deleteJerseyDuty(prior.id);
assert.throws(() => BT.storage.upsertJerseyDuty(prior), /existiert nicht mehr/);
const stored = JSON.stringify(BT.storage.load());
assert.equal(JSON.parse(stored).jerseyDuties.length, before + 1);
assert(saves > 0, 'All changes enter the team sync queue.');
const protectedData = protectWorkspace({ games: [] }, JSON.parse(stored));
assert.equal(protectedData.jerseyDuties.length, before + 1, 'Older clients must not drop the collection.');
assert.throws(() => protectWorkspace({ jerseyDuties: {} }, {}), /Waschdienste/);
BT.sync.getState = () => ({ user: { role: 'viewer' } });
host.replaceChildren(); BT.jerseys.render(host);
assert.equal(host.querySelectorAll('[data-action]').length, 0, 'Viewers see assignments without write controls.');
dom.window.close();
console.log('CourtHub: Waschdienst, Satzsperre, Rückgabe, Saisonverteilung, Kaderhistorie, Reload und Sync erfolgreich.');
