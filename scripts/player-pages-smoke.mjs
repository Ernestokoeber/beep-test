import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { JSDOM } from 'jsdom';
const html = readFileSync(new URL('../index.html', import.meta.url), 'utf8');
const dom = new JSDOM(html, {url:'https://coach.example/#/players',runScripts:'outside-only'});
const w = dom.window;
w.scrollTo = () => {};
for (const name of ['util','development-core','storage','levels','ratings','heatmap','stats','players']) {
  w.eval(readFileSync(new URL('../js/' + name + '.js', import.meta.url),'utf8'));
}
let state = {};
w.BT.navigation = {getState:()=>state,setState:patch=>{state={...state,...patch};},back:()=>{}};
const p = w.BT.storage.upsertPlayer({name:'Lena <Guard>',position:'Guard',jerseyNumber:'7',goals:[{id:'g1',title:'Linke Hand',status:'active',progress:25,feedback:[]}]});
const host = w.document.querySelector('#app');
w.BT.players.renderDetail(host,p.id);
assert(host.querySelector('[data-player-page="overview"]'), 'Eine eigenständige Profilübersicht fehlt.');
assert.equal(host.querySelector('[data-role="name"]').textContent,p.name);
assert.equal(host.querySelector('[data-role="goal-form"]'),null,'Zielformular gehört auf die Entwicklungsseite.');
assert(host.querySelector('a[href="#/player/' + p.id + '/shots"]'),'Würfe öffnen eine eigene Seite.');
assert.equal(host.querySelector('Guard'),null,'Name wird nicht als HTML ausgewertet.');
for (const section of ['development','shots','fitness','history']) {
  host.replaceChildren(); w.BT.players.renderDetail(host,p.id,section);
  assert(host.querySelector('[data-player-page="' + section + '"]'));
  assert.equal(host.querySelectorAll('[data-player-page]').length,1);
}
host.replaceChildren(); w.BT.players.renderDetail(host,p.id,'development');
host.querySelector('[data-action="new-goal"]').click();
const goal=host.querySelector('[data-role="goal-form"]');
goal.elements.title.value='Abschluss links'; goal.dispatchEvent(new w.Event('input',{bubbles:true}));
host.replaceChildren(); w.BT.players.renderDetail(host,p.id,'development');
assert.equal(host.querySelector('[name="title"]').value,'Abschluss links','Zielentwurf bleibt erhalten.');
const feedback=host.querySelector('[data-goal-feedback]');
feedback.value='Weiter am linken Abschluss arbeiten'; feedback.dispatchEvent(new w.Event('input',{bubbles:true}));
host.replaceChildren(); w.BT.players.renderDetail(host,p.id,'development');
assert.equal(host.querySelector('[data-goal-feedback]').value,'Weiter am linken Abschluss arbeiten','Trainerfeedback bleibt als Entwurf erhalten.');
host.querySelector('[data-goal-action="feedback"]').click();
assert.equal(host.querySelector('[data-goal-feedback]').value,'','Gespeichertes Feedback wird nicht erneut eingesetzt.');
state={}; host.replaceChildren(); w.BT.players.renderDetail(host,p.id,'report');
host.querySelector('[data-action="new-goal"]').click();
host.querySelector('[name="title"]').value='Berichtentwurf';
host.querySelector('[name="title"]').dispatchEvent(new w.Event('input',{bubbles:true}));
host.replaceChildren(); w.BT.players.renderDetail(host,p.id,'report');
assert.equal(host.querySelector('[name="title"]').value,'Berichtentwurf');
w.BT.stats.endedTrainings=()=>[{shotMap:[{playerId:p.id,x:0.5,y:0.5,made:true}]}];
host.replaceChildren(); w.BT.players.renderDetail(host,p.id,'shots');
assert(host.querySelector('[data-role="player-heatmap-cells"]').children.length>0);
const shots=host.querySelector('input[name="heatmap-view"][value="shots"]'); shots.checked=true; shots.dispatchEvent(new w.Event('change',{bubbles:true}));
assert.equal(host.querySelector('[data-role="player-heatmap-cells"]').children.length,0,'Zonen werden beim Wechsel ausgeblendet.');
assert(host.querySelector('[data-role="player-heatmap-shots"]').children.length>0,'Einzelwürfe werden angezeigt.');
state={}; host.replaceChildren(); w.BT.players.render(host);
const search=host.querySelector('[data-role="player-search"]');
assert(search,'Spielersuche fehlt.');
search.value='Nicht vorhanden'; search.dispatchEvent(new w.Event('input',{bubbles:true}));
assert.equal(host.querySelectorAll('[data-player-link]').length,0);
search.value='Lena'; search.dispatchEvent(new w.Event('input',{bubbles:true}));
assert.equal(host.querySelectorAll('[data-player-link]').length,1);
host.replaceChildren(); w.BT.players.render(host);
assert.equal(host.querySelector('[data-role="player-search"]').value,'Lena');
state={}; host.replaceChildren(); w.BT.players.renderEditor(host,p.id);
const form=host.querySelector('[data-role="player-form"]');
form.elements.name.value='Lena geändert'; form.dispatchEvent(new w.Event('input',{bubbles:true}));
host.replaceChildren(); w.BT.players.renderEditor(host,p.id);
assert.equal(host.querySelector('[name="name"]').value,'Lena geändert','Profilentwurf bleibt erhalten.');
dom.window.close();
console.log('Spielerseiten: Trennung, Suche, sichere Namen und Formularentwürfe geprüft.');
