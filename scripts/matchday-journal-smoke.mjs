import assert from 'node:assert/strict';
import {IDBFactory} from 'fake-indexeddb';
import {openMatchdayJournal} from '../js/matchday/journal.mjs';
import {createMatchdayBridge} from '../js/matchday/bridge.mjs';
import {emptyDraft,reviseMatchday,selectDraft} from '../js/matchday/model.mjs';
const idb=new IDBFactory(),scope={organizationId:'club',actorId:'coach'};
const j=await openMatchdayJournal(scope,idb);
const revision=(id,parents,goals='')=>({id,parents,actorId:'coach',deviceId:'phone',recordedAt:'2026-09-29T10:00:00Z',value:{...emptyDraft(),goals}});
const a=reviseMatchday(undefined,revision('a',[]));
await j.append('g',a);const receipt=(await j.pending()).map(({gameId,stamp})=>({gameId,stamp}));
const b=reviseMatchday(a,revision('b',['a'],'Box-out'));await j.append('g',b);await j.ack(receipt);
assert.equal((await j.pending()).length,1);
assert.deepEqual(await (await openMatchdayJournal(scope,idb)).read('g'),b);
for(const other of [{...scope,actorId:'other'},{...scope,organizationId:'other'}])assert.equal(await(await openMatchdayJournal(other,idb)).read('g'),undefined);
const c=reviseMatchday(a,revision('c',['a'],'Parallel'));
await Promise.all([j.append('g',b),j.append('g',c)]);assert.equal(selectDraft(await j.read('g')).conflict,true);
const bridge=createMatchdayBridge(async()=>j);
await assert.rejects(()=>bridge.beforeSend({games:[]},scope),e=>e.code==='deletion');
const prepared=await bridge.beforeSend({games:[{id:'g',liveStats:{sentinel:true}}]},scope);
assert.deepEqual(prepared.data.games[0].liveStats,{sentinel:true});assert.equal(prepared.receipt.length,1);
const accepted=await bridge.mergeAccepted({games:[{id:'g',matchday:b}]},{games:[{id:'g',matchday:c}]},scope);
assert.equal(accepted.games[0].matchday.revisions.length,3);
await bridge.ack(prepared.receipt,scope);assert.equal(await bridge.hasPending(scope),false);
await assert.rejects(()=>openMatchdayJournal(scope,null),/Offline/);
// An actual aborted IndexedDB write must not be reported as success.
const db=await new Promise(resolve=>{const r=idb.open('courthub-matchday-v1');r.onsuccess=()=>resolve(r.result);});
const proto=Object.getPrototypeOf(db.transaction('drafts','readwrite').objectStore('drafts'));
const put=proto.put;proto.put=function(...args){const result=put.apply(this,args);this.transaction.abort();return result;};
await assert.rejects(()=>j.append('new',a));proto.put=put;
assert.equal(await j.read('new'),undefined);
console.log('Matchday journal: durable writes, scope, concurrent branches, receipts, abort and overlay passed.');
