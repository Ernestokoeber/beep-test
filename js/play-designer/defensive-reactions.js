export const DEFENDER_REACTION_DELAY = 0.18;
export const SCREEN_HOLD_DURATION = 0.36;

function number(value, fallback = 0) {
  const parsed = Number(value);
  return Number.isFinite(parsed) ? parsed : fallback;
}

export function isAutomaticDefenseMotion(action) {
  return action?.autoGenerated === 'defender-follow';
}

function deterministicFollowId(sourceMotionId, defenderId) {
  return `auto-follow:${String(sourceMotionId)}:${String(defenderId)}`;
}

function translatedPath(motion, offense, defender, core) {
  const source = Array.isArray(motion.path) && motion.path.length >= 2
    ? motion.path
    : [offense];
  const dx = defender.x - offense.x;
  const dy = defender.y - offense.y;
  return source.map(point => core.point({
    x: number(point?.x, offense.x) + dx,
    y: number(point?.y, offense.y) + dy
  }));
}

function matchingScreens(transition, offenseId, defenderId) {
  return transition.screens
    .filter(screen => screen.targetDefenderId === defenderId)
    .filter(screen => !screen.beneficiaryId || screen.beneficiaryId === offenseId)
    .sort((left, right) => number(left.start) - number(right.start));
}

function screenHolds(transition, motion, defenderId) {
  const motionStart = number(motion.start);
  const motionEnd = motionStart + Math.max(0.15, number(motion.duration, 0.15));
  const reaction = Math.min(
    DEFENDER_REACTION_DELAY,
    Math.max(0, number(motion.duration, 0.15) - 0.15)
  );
  const followerStart = motionStart + reaction;
  const followerDuration = Math.max(0.15, motionEnd - followerStart);
  let availableHold = Math.max(0, followerDuration - 0.15);

  return matchingScreens(transition, motion.elementId, defenderId)
    .map(screen => {
      if (availableHold <= 0 || number(screen.start) > motionEnd) return null;
      const at = Math.max(followerStart, Math.min(motionEnd, number(screen.start)));
      const duration = Math.min(
        SCREEN_HOLD_DURATION,
        Math.max(0.18, number(screen.duration, SCREEN_HOLD_DURATION) * 0.45),
        availableHold
      );
      availableHold -= duration;
      return duration > 0.01
        ? { at, duration, screenId: String(screen.id) }
        : null;
    })
    .filter(Boolean);
}

function preferredDefender(transition, offenseId, candidates) {
  const targetIds = transition.screens
    .filter(screen => screen.beneficiaryId === offenseId && screen.targetDefenderId)
    .map(screen => String(screen.targetDefenderId));
  return candidates.find(defender => targetIds.includes(defender.id)) || null;
}

function nearestDefender(offense, candidates, core) {
  return [...candidates].sort((left, right) =>
    core.distance(offense, left) - core.distance(offense, right)
      || String(left.id).localeCompare(String(right.id))
  )[0] || null;
}

export function refreshAutomaticDefense(step, next, core) {
  if (!step?.transition || !next) return step;
  const transition = {
    motions: Array.isArray(step.transition.motions) ? step.transition.motions : [],
    passes: Array.isArray(step.transition.passes) ? step.transition.passes : [],
    screens: Array.isArray(step.transition.screens) ? step.transition.screens : []
  };
  const automatic = transition.motions.filter(isAutomaticDefenseMotion);
  const manual = transition.motions.filter(action => !isAutomaticDefenseMotion(action));
  const manualDefenseIds = new Set(manual
    .filter(action => core.elementById(step, action.elementId)?.type === 'defense')
    .map(action => action.elementId));

  automatic.forEach(action => {
    if (manualDefenseIds.has(action.elementId)) return;
    const source = core.elementById(step, action.elementId);
    const target = core.elementById(next, action.elementId);
    if (source && target) Object.assign(target, core.point(source));
  });
  transition.motions = manual;

  const available = core.elements(step, 'defense')
    .filter(defender => defender.defenseMode !== 'zone')
    .filter(defender => !manualDefenseIds.has(defender.id));
  const reserved = new Set();
  const offenseMotions = manual
    .filter(action => core.elementById(step, action.elementId)?.type === 'offense')
    .sort((left, right) => {
      const leftTargeted = transition.screens.some(screen =>
        screen.beneficiaryId === left.elementId && screen.targetDefenderId
      );
      const rightTargeted = transition.screens.some(screen =>
        screen.beneficiaryId === right.elementId && screen.targetDefenderId
      );
      return Number(rightTargeted) - Number(leftTargeted)
        || number(left.start) - number(right.start);
    });

  offenseMotions.forEach(motion => {
    const offense = core.elementById(step, motion.elementId);
    if (!offense) return;
    const candidates = available.filter(defender => !reserved.has(defender.id));
    const defender = preferredDefender(transition, offense.id, candidates)
      || nearestDefender(offense, candidates, core);
    if (!defender) return;
    const target = core.elementById(next, defender.id);
    if (!target) return;

    const path = translatedPath(motion, offense, defender, core);
    if (path.length < 2) return;
    const reaction = Math.min(
      DEFENDER_REACTION_DELAY,
      Math.max(0, number(motion.duration, 0.15) - 0.15)
    );
    const start = number(motion.start) + reaction;
    const duration = Math.max(0.15, number(motion.duration, 0.15) - reaction);
    const holds = screenHolds(transition, motion, defender.id);

    transition.motions.push({
      id: deterministicFollowId(motion.id, defender.id),
      type: 'move',
      elementId: defender.id,
      kind: 'run',
      relation: 'simultaneous',
      start,
      duration,
      path,
      autoGenerated: 'defender-follow',
      followsId: offense.id,
      sourceMotionId: String(motion.id),
      ...(holds.length ? { holds } : {})
    });
    Object.assign(target, path.at(-1));
    reserved.add(defender.id);
  });

  step.transition = transition;
  return step;
}

export function motionProgress(action, elapsedInput) {
  const start = Math.max(0, number(action?.start));
  const duration = Math.max(0.001, number(action?.duration, 0.001));
  const elapsed = Math.max(0, number(elapsedInput));
  if (elapsed <= start) return 0;
  if (elapsed >= start + duration) return 1;

  const holds = (Array.isArray(action?.holds) ? action.holds : [])
    .map(hold => ({
      at: Math.max(start, Math.min(start + duration, number(hold?.at, start))),
      duration: Math.max(0, number(hold?.duration))
    }))
    .sort((left, right) => left.at - right.at);
  const totalHold = Math.min(
    Math.max(0, duration - 0.001),
    holds.reduce((sum, hold) => sum + hold.duration, 0)
  );
  const paused = holds.reduce((sum, hold) => {
    if (elapsed <= hold.at) return sum;
    return sum + Math.min(hold.duration, elapsed - hold.at);
  }, 0);
  const travelDuration = Math.max(0.001, duration - totalHold);
  return Math.max(0, Math.min(1, (elapsed - start - paused) / travelDuration));
}
