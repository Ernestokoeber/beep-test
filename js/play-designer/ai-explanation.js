import { normalizeRecordedBoard } from './phase-recorder-core.js';

function numeric(value) {
  const parsed = Number(value);
  return Number.isFinite(parsed) ? Number(parsed.toFixed(2)) : 0;
}

function point(value) {
  return value ? { x: numeric(value.x), y: numeric(value.y) } : null;
}

function actionBase(action) {
  return {
    actor: null,
    receiver: null,
    beneficiary: null,
    targetDefender: null,
    kind: null,
    relation: action.relation || 'after',
    groupId: action.groupId || null,
    groupType: action.groupType || null,
    groupRole: action.groupRole || null,
    start: numeric(action.start),
    duration: numeric(action.duration),
    end: null,
    angle: null,
    automatic: action.autoGenerated === 'defender-follow'
  };
}

function serializeAction(action, step, core) {
  const base = actionBase(action);
  if (action.type === 'move') {
    return {
      type: 'move',
      ...base,
      actor: action.elementId || null,
      kind: action.kind || 'run',
      end: point((action.path || []).at(-1))
    };
  }
  if (action.type === 'pass') {
    return {
      type: 'pass',
      ...base,
      actor: action.fromId || null,
      receiver: action.toId || null,
      kind: 'pass',
      end: point(core.elementById(step, action.toId)),
      curve: numeric(action.curve)
    };
  }
  return {
    type: 'screen',
    ...base,
    actor: action.elementId || null,
    beneficiary: action.beneficiaryId || null,
    targetDefender: action.targetDefenderId || null,
    kind: 'screen',
    end: point(action),
    angle: numeric(action.angle)
  };
}

export function serializeTactic(boardInput, core) {
  const board = normalizeRecordedBoard(boardInput, core);
  return {
    schemaVersion: 3,
    title: board.title,
    category: board.category,
    description: board.description,
    tags: board.tags,
    phases: board.steps.map((step, index) => {
      const transition = step.transition || core.emptyTransition();
      const actions = [
        ...(transition.motions || []),
        ...(transition.passes || []),
        ...(transition.screens || [])
      ].map((action) => serializeAction(action, step, core)).sort((left, right) =>
        left.start - right.start || left.duration - right.duration || left.type.localeCompare(right.type)
      );
      const ball = core.elements(step, 'ball')[0];
      return {
        number: index + 1,
        instruction: String(step.instruction || ''),
        duration: numeric(step.duration),
        offense: core.elements(step, 'offense').map((player) => ({
          id: player.id,
          role: player.role,
          x: numeric(player.x),
          y: numeric(player.y)
        })),
        defense: core.elements(step, 'defense').map((player) => ({
          id: player.id,
          role: player.role,
          mode: player.defenseMode === 'zone' ? 'zone' : 'man',
          x: numeric(player.x),
          y: numeric(player.y)
        })),
        ball: point(ball),
        actions
      };
    })
  };
}

