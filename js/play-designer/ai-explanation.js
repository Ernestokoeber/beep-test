async function copyText(text) {
  if (window.navigator.clipboard?.writeText) return window.navigator.clipboard.writeText(text);
  const field = document.createElement('textarea');
  field.value = text;
  field.setAttribute('readonly', '');
  field.style.position = 'fixed';
  field.style.opacity = '0';
  document.body.append(field);
  field.select();
  document.execCommand?.('copy');
  field.remove();
}

export async function openAIExplanation({ board, core, saveDescription, toast }) {
  injectStyles();
  const backdrop = document.createElement('div');
  backdrop.className = 'chai-backdrop';
  backdrop.innerHTML = `
    <section class="chai-dialog" role="dialog" aria-modal="true" aria-labelledby="chai-title" data-ai-explanation>
      <header class="chai-head"><h2 id="chai-title">Spielzug erklären</h2><button class="chai-close" type="button" data-ai-close aria-label="Schließen">×</button></header>
      <div class="chai-body"><p class="chai-status" data-ai-status>Der Spielzug wird anhand seiner Phasen analysiert …</p><div class="chai-copy" data-ai-copy-content></div><p class="chai-meta" data-ai-meta hidden></p></div>
      <footer class="chai-actions"><button class="chai-btn" type="button" data-ai-copy disabled>Erklärung kopieren</button></footer>
    </section>`;
  document.body.append(backdrop);
  const dialog = backdrop.querySelector('[data-ai-explanation]');
  const status = backdrop.querySelector('[data-ai-status]');
  const content = backdrop.querySelector('[data-ai-copy-content]');
  const meta = backdrop.querySelector('[data-ai-meta]');
  const copyButton = backdrop.querySelector('[data-ai-copy]');
  const actions = backdrop.querySelector('.chai-actions');
  const close = () => backdrop.remove();
  backdrop.querySelector('[data-ai-close]').addEventListener('click', close);
  backdrop.addEventListener('click', (event) => { if (event.target === backdrop) close(); });

  try {
    const response = await window.BT.api.ai('explainTactic', { tactic: serializeTactic(board, core) });
    const points = Array.isArray(response.coachingPoints) ? response.coachingPoints.map(String) : [];
    const explanation = String(response.text || '');
    const heading = document.createElement('h3');
    heading.textContent = 'Erklärung';
    const paragraph = document.createElement('p');
    paragraph.textContent = explanation;
    const pointsHeading = document.createElement('h3');
    pointsHeading.textContent = 'Coaching-Punkte';
    const list = document.createElement('ul');
    list.className = 'chai-points';
    points.forEach((pointValue) => {
      const item = document.createElement('li');
      item.textContent = pointValue;
      list.append(item);
    });
    content.replaceChildren(heading, paragraph, pointsHeading, list);
    status.textContent = 'Die Erklärung ist bereit.';
    meta.hidden = false;
    meta.textContent = [response.model, response.requestId ? `Request-ID: ${response.requestId}` : ''].filter(Boolean).join(' · ');
    const copyValue = [explanation, points.length ? `Coaching-Punkte:\n${points.map((pointValue) => `• ${pointValue}`).join('\n')}` : ''].filter(Boolean).join('\n\n');
    copyButton.disabled = false;
    copyButton.addEventListener('click', async () => {
      await copyText(copyValue);
      toast?.('Erklärung kopiert.');
    });

    if (core.canEdit()) {
      const applyButton = document.createElement('button');
      applyButton.className = 'chai-btn chai-btn-primary';
      applyButton.type = 'button';
      applyButton.dataset.aiApply = 'true';
      applyButton.textContent = 'Als Coaching Points übernehmen';
      applyButton.addEventListener('click', () => {
        if (!window.confirm('Bestehende Coaching Points durch diese KI-Hinweise ersetzen?')) return;
        board.description = points.join(' · ').slice(0, 400);
        saveDescription?.(board);
        toast?.('Coaching Points übernommen.');
      });
      actions.append(applyButton);
    }
  } catch (error) {
    status.textContent = error.message || 'Die Taktikerklärung konnte nicht erstellt werden.';
    if (error.requestId) {
      meta.hidden = false;
      meta.textContent = `Request-ID: ${error.requestId}`;
    }
  }
  return dialog;
}

